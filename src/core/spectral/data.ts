/**
 * Status T 密度滤光片响应（R/G/B 三通道，峰值归一化）
 * 宽带高斯近似，中心对准各油墨补色波段：
 * 红通道（测青）峰值 ~630nm，绿通道（测品红）~530nm，蓝通道（测黄）~450nm，
 * 带间保留少量重叠以模拟真实滤光片串扰。
 */
function gaussStatus(center: number, width: number): number[] {
  return WAVELENGTHS.map((w) => Math.exp(-0.5 * ((w - center) / width) ** 2));
}
const ST_R = gaussStatus(640, 48);
const ST_G = gaussStatus(545, 42);
const ST_B = gaussStatus(455, 42);
const normMax = (arr: number[]): number[] => {
  const m = Math.max(...arr);
  return arr.map((v) => v / m);
};
const ST_RN = normMax(ST_R);
const ST_GN = normMax(ST_G);
const ST_BN = normMax(ST_B);
export const STATUS_T: ReadonlyArray<readonly [number, number, number]> = WAVELENGTHS.map(
  (_, i) => [ST_RN[i], ST_GN[i], ST_BN[i]],
);

